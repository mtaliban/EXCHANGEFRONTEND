interface I18nState {
  lang: Lang;
  setLang: (l: Lang) => void;
  toggle: () => void;
}

export const useI18n = create<I18nState>()(
  persist(
    (set, get) => ({
      lang: 'sw',
      setLang: (l) => set({ lang: l }),
      toggle: () => set({ lang: get().lang === 'sw' ? 'en' : 'sw' }),
    }),
    { name: 'kv_lang' }
  )
);

export function useT() {
  const lang = useI18n((s) => s.lang);
  return (key: string, fallback?: string) => dict[lang][key] || fallback || key;
}
